def main():
    fixed_kanji = {"surprise": "びっくり"}  # N4 kanji 欄位誤植修正
    for level, table in MN.items():
        path = os.path.join(DB, f"{level}.json")
        data = json.load(open(path, encoding="utf-8"))
        vocab = data["vocab"] if isinstance(data, dict) else data
        miss = []
        for e in vocab:
            if e.get("kanji") in fixed_kanji:
                e["kanji"] = fixed_kanji[e["kanji"]]
            mn = table.get(e["kana"])
            if not mn:
                miss.append(e["kana"])
                continue
            e["mnemonic"], e["image"] = mn
        json.dump(data, open(path, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=2)
        print(f"{level}: {len(vocab)} 筆，補諧音 {len(vocab)-len(miss)}，缺 {miss}")

if __name__ == "__main__":
    main()
